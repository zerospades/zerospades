/**** CPU RADIOSITY (FASTER?) *****/

uniform sampler3D ambientShadowTexture;
uniform sampler3D radiosityTextureFlat;
uniform sampler3D radiosityTextureX;
uniform sampler3D radiosityTextureY;
uniform sampler3D radiosityTextureZ;
varying vec3 radiosityTextureCoord;
varying vec3 ambientShadowTextureCoord;
varying vec3 normalVarying;
uniform vec3 ambientColor;
uniform vec3 skyLightColor;

// The sun's light scales what the map bounces of it; the daylight, the sky's.
uniform float sunlight;
uniform float daylight;

vec3 DecodeRadiosityValue(vec3 val) {
	// reverse bias
	val *= 1023.0 / 1022.0;
	val = (val * 2.0) - 1.0;
#if USE_RADIOSITY == 1
	// the low-precision radiosity texture uses a non-linear encoding
	val *= val * sign(val);
#endif
	return val;
}

vec3 EvaluateRadiosity(float detailAmbientOcclusion, float ssao) {
	vec3 col = DecodeRadiosityValue(texture3D(radiosityTextureFlat, radiosityTextureCoord).xyz);
	vec3 normal = normalize(normalVarying);
	col += normal.x * DecodeRadiosityValue(texture3D(radiosityTextureX, radiosityTextureCoord).xyz);
	col += normal.y * DecodeRadiosityValue(texture3D(radiosityTextureY, radiosityTextureCoord).xyz);
	col += normal.z * DecodeRadiosityValue(texture3D(radiosityTextureZ, radiosityTextureCoord).xyz);
	col = max(col, 0.0);
	col *= 1.5 * ssao * sunlight;

	detailAmbientOcclusion *= ssao;

	// ambient occlusion
	vec2 ambTexVal = texture3D(ambientShadowTexture, ambientShadowTextureCoord).xy;
	float amb = ambTexVal.x / max(ambTexVal.y, 0.25);
	amb = max(amb, 0.0); // for some reason, mainTexture value becomes negative

	// mix ambient occlusion values generated by two different methods somehow
	amb = mix(sqrt(amb * detailAmbientOcclusion), min(amb, detailAmbientOcclusion), 0.5);

	amb *= (0.8 - normalVarying.z * 0.2) * daylight;
	col += amb * ambientColor;

	return col;
}

vec3 EvaluateSoftReflections(float detailAmbientOcclusion, vec3 direction, float ssao) {
	vec3 col = DecodeRadiosityValue(texture3D(radiosityTextureFlat, radiosityTextureCoord).xyz);
	vec3 normal = normalize(normalVarying);
	col += normal.x * DecodeRadiosityValue(texture3D(radiosityTextureX, radiosityTextureCoord).xyz);
	col += normal.y * DecodeRadiosityValue(texture3D(radiosityTextureY, radiosityTextureCoord).xyz);
	col += normal.z * DecodeRadiosityValue(texture3D(radiosityTextureZ, radiosityTextureCoord).xyz);
	col = max(col, 0.0);
	col *= 1.5 * ssao * sunlight;

	detailAmbientOcclusion *= ssao;

	// ambient occlusion
	float amb = texture3D(ambientShadowTexture, ambientShadowTextureCoord).x;
	amb = max(amb, 0.0); // for some reason, mainTexture value becomes negative
	amb *= amb; // darken

	// mix ambient occlusion values generated by two different methods somehow
	amb = mix(sqrt(amb * detailAmbientOcclusion), min(amb, detailAmbientOcclusion), 0.5);

	amb *= (0.8 - normalVarying.z * 0.2) * daylight;

	return col + skyLightColor * amb;
}