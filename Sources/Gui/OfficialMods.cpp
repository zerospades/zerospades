		class OfficialModsChecker::Query final : public Thread {
			OfficialModsChecker& owner;

		public:
			Query(OfficialModsChecker& owner) : owner(owner) {}

			void Run() override {
				OfficialModsListing listing;
				std::string err;
				try {
					err = FetchOfficialModsListing(listing);
				} catch (const std::exception& ex) {
					err = ex.what();
				}
				if (!err.empty()) {
					SPLog("[!] Official mods check: %s", err.c_str());
					owner.Finish(nullptr);
					return;
				}
				owner.Finish(&listing);
			}
		};

		OfficialModsChecker& OfficialModsChecker::Get() {
			// Deliberately never destroyed: the worker may still be waiting on the
			// network when the process exits, and must not outlive what it writes to.
			static OfficialModsChecker* instance = new OfficialModsChecker();
			return *instance;
		}

		void OfficialModsChecker::Start() {
			{
				std::lock_guard<std::mutex> guard(mutex);
				if (started)
					return;
				started = true;
			}
			// A player who never installed the official mods is not told about them.
			std::optional<OfficialModsVersion> installed = ReadInstalledOfficialMods();
			{
				std::lock_guard<std::mutex> guard(mutex);
				if (!installed) {
					result.state = State::NotInstalled;
					return;
				}
				installedVersion = *installed;
				result.installedVersion = installedVersion;
				result.state = State::Checking;
			}

			auto* query = new Query(*this);
			query->Start();
			query->MarkForAutoDeletion();
		}

		OfficialModsChecker::Result OfficialModsChecker::GetResult() {
			std::lock_guard<std::mutex> guard(mutex);
			return result;
		}

		void OfficialModsChecker::Installed(const OfficialModsVersion& version) {
			std::lock_guard<std::mutex> guard(mutex);
			installedVersion = version;
			result.installedVersion = version;
			// The install fetched the latest release, so it is up to date; a newer
			// release that needs a newer ZeroSpades still is, though.
			if (result.state == State::GameUpdateNeeded && version < result.latestVersion)
				return;
			result.state = State::UpToDate;
		}

		void OfficialModsChecker::Finish(const OfficialModsListing* listing) {
			std::lock_guard<std::mutex> guard(mutex);
			Result r;
			r.installedVersion = installedVersion;
			if (!listing) {
				r.state = State::Failed;
			} else if (listing->latestCompatible &&
			           installedVersion < listing->latestCompatible->version) {
				r.state = State::UpdateAvailable;
				r.latestVersion = listing->latestCompatible->version;
			} else if (listing->newestIncompatible &&
			           installedVersion < *listing->newestIncompatible) {
				r.state = State::GameUpdateNeeded;
				r.latestVersion = *listing->newestIncompatible;
			} else {
				r.state = State::UpToDate;
			}

			// An install that finished while the check was running already
			// answered it.
			if (result.state == State::UpToDate && r.state == State::UpdateAvailable)
				return;
			result = r;

			if (r.state == State::UpdateAvailable || r.state == State::GameUpdateNeeded)
				SPLog("Official mods check: %s installed, %s is available%s.",
				      installedVersion.ToString().c_str(), r.latestVersion.ToString().c_str(),
				      r.state == State::GameUpdateNeeded ? " (needs a newer ZeroSpades)" : "");
		}
